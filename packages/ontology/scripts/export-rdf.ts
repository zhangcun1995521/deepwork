#!/usr/bin/env node
/**
 * Export a domain as RDF/XML, for a graph viewer to draw.
 *
 *   node packages/ontology/scripts/export-rdf.ts <domain-directory> [-o <file>]
 *     [--base <iri>] [--instances] [--limit <n>]
 *
 * Written for Microsoft's Ontology Playground, which imports RDF/XML and renders a clickable graph.
 * Nothing here is Playground-specific, though: the output is ordinary OWL, and any RDF viewer will
 * read it.
 *
 * **Schema only by default, and that is a judgement rather than a shortcut.** The graph is a picture
 * of what a domain *is*, and a real domain is thousands of instances: one produced by this repository
 * carries four thousand, which a viewer either draws as an unreadable hairball or silently collapses
 * into a hierarchy summary. What a reader wants from a picture is the twenty types and the relations
 * between them — the part a human can hold in their head. `--instances` is here for the cases that
 * need evidence, not for the default case.
 *
 * **What the export cannot carry, stated rather than papered over.** This domain declares no
 * cardinality on its relations, no type hierarchy, and no `kind`/`role`/`phase`/`relator` distinction.
 * A viewer that draws `one-to-many` therefore has nothing to draw, and a picture that looks complete
 * will be missing exactly what the modelling layer knows and the projection cannot show. That loss is
 * the reason the notice below is emitted into the file: an exported graph is a projection, and a
 * projection must not be mistaken for the source.
 */

import { writeFileSync } from 'node:fs'
import { loadGraph, type OntologyGraph } from '../src/engine/graph.ts'

/** RDF/XML escaping. `>` is escaped too: it is legal bare, and it is also how a stray `<` becomes visible. */
function escape(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    // Control characters are not representable in XML 1.0 at all; a literal tab or newline is, and is
    // kept because instance text is often multi-line prose.
    .replaceAll(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
}

/**
 * A field name as an XML QName local part.
 *
 * Instance keys are the domain's own words and are not guaranteed to be NCNames; a name that is not
 * one would produce a file no parser accepts, and the failure would look like a broken export rather
 * than a bad key. Invalid characters become `_`, and a leading digit gains a prefix because an NCName
 * may not start with one.
 */
function localName(raw: string): string {
  const replaced = raw.replaceAll(/[^\p{L}\p{N}._-]/gu, '_')
  return /^[0-9]/.test(replaced) ? `_${replaced}` : replaced === '' ? '_' : replaced
}

/** One field's value as RDF object elements. Lists become repeated statements, which is what RDF has. */
function valueElements(
  prefix: string,
  name: string,
  value: unknown,
  depth: number,
): string[] {
  if (value === null || value === undefined) return []
  const property = `${prefix}:${localName(name)}`
  if (Array.isArray(value)) {
    return value.flatMap((item) => valueElements(prefix, name, item, depth))
  }
  if (typeof value === 'object') {
    // A nested map is flattened with a dot rather than turned into a blank node: the viewer lists a
    // node's properties, and a reader looking for "which auth type" is better served by one line
    // than by a nested object they have to expand. Depth is capped so a malformed instance cannot
    // recurse forever.
    if (depth > 3) return []
    return Object.entries(value as Record<string, unknown>).flatMap(([key, nested]) =>
      valueElements(prefix, `${name}.${key}`, nested, depth + 1),
    )
  }
  const text =
    typeof value === 'string'
      ? value
      : typeof value === 'number' || typeof value === 'boolean'
        ? String(value)
        : JSON.stringify(value)
  if (text.length === 0) return []
  const datatype =
    typeof value === 'number'
      ? 'http://www.w3.org/2001/XMLSchema#decimal'
      : typeof value === 'boolean'
        ? 'http://www.w3.org/2001/XMLSchema#boolean'
        : 'http://www.w3.org/2001/XMLSchema#string'
  return [`    <${property} rdf:datatype="${datatype}">${escape(text)}</${property}>`]
}

/** The whole document. */
function render(graph: OntologyGraph, request: { base: string; instances: number }): string {
  const base = request.base.replace(/#$/, '')
  const iri = (name: string): string => `${base}#${encodeURIComponent(name).replaceAll('%', '_')}`

  const lines: string[] = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by @zhangcun123/ontology: a projection for graph viewers, not a source. -->',
    `<!-- ${graph.schema.objectTypes.size} classes, ${graph.schema.linkTypes.size} relations, ` +
      `${request.instances === 0 ? 'no instances (schema only)' : `${request.instances} instances`}. -->`,
    '<!-- This domain declares no cardinality, no type hierarchy and no kind/role/phase/relator ' +
      'distinction, so a viewer cannot draw them. Absence in this picture is not absence in the ' +
      'domain. -->',
    '<rdf:RDF',
    '  xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"',
    '  xmlns:rdfs="http://www.w3.org/2000/01/rdf-schema#"',
    '  xmlns:owl="http://www.w3.org/2002/07/owl#"',
    `  xmlns:dw="${base}#">`,
  ]

  for (const type of graph.schema.objectTypes.values()) {
    lines.push(`  <owl:Class rdf:about="${iri(type.name)}">`)
    lines.push(`    <rdfs:label>${escape(type.name)}</rdfs:label>`)
    if (type.description !== undefined && type.description.length > 0) {
      // Only the first paragraph: a domain's descriptions are written for a reader of the schema, and
      // the full text on a node makes the property panel unreadable without adding a fact.
      const first = type.description.split('\n')[0]?.trim() ?? ''
      if (first.length > 0) lines.push(`    <rdfs:comment>${escape(first)}</rdfs:comment>`)
    }
    const count = graph.byType.get(type.name)?.length ?? 0
    // A literal, not an `rdfs:seeAlso` reference: a viewer draws every resource an `rdf:resource`
    // points at, so a pointer at "the type plus its instance count" would arrive as twenty extra
    // nodes of its own making. A typed literal is a property of the class and creates nothing.
    lines.push(
      `    <dw:instances rdf:datatype="http://www.w3.org/2001/XMLSchema#integer">${count}</dw:instances>`,
    )
    lines.push('  </owl:Class>')
  }

  for (const link of graph.schema.linkTypes.values()) {
    lines.push(`  <owl:ObjectProperty rdf:about="${iri(link.name)}">`)
    lines.push(`    <rdfs:label>${escape(link.name)}</rdfs:label>`)
    lines.push(`    <rdfs:domain rdf:resource="${iri(link.from)}"/>`)
    lines.push(`    <rdfs:range rdf:resource="${iri(link.to)}"/>`)
    if (link.description !== undefined && link.description.length > 0) {
      lines.push(`    <rdfs:comment>${escape(link.description.split('\n')[0]?.trim() ?? '')}</rdfs:comment>`)
    }
    if (link.via !== undefined) {
      // The field the edge is derived from, as a literal for the reason the instance count is one:
      // a resource reference would be drawn as a node that exists nowhere in the domain.
      lines.push(`    <dw:viaField rdf:datatype="http://www.w3.org/2001/XMLSchema#string">${escape(link.via)}</dw:viaField>`)
    }
    lines.push('  </owl:ObjectProperty>')
  }

  if (request.instances > 0) {
    for (const object of graph.objects.slice(0, request.instances)) {
      lines.push(`  <owl:NamedIndividual rdf:about="${iri(`${object.type}_${object.id}`)}">`)
      lines.push(`    <rdf:type rdf:resource="${iri(object.type)}"/>`)
      lines.push(`    <rdfs:label>${escape(object.id)}</rdfs:label>`)
      for (const [key, value] of Object.entries(object.data)) {
        lines.push(...valueElements('dw', key, value, 0))
      }
      lines.push('  </owl:NamedIndividual>')
    }
  }

  lines.push('</rdf:RDF>', '')
  return lines.join('\n')
}

const args = process.argv.slice(2)
const root = args.find((arg) => !arg.startsWith('-'))
if (root === undefined) {
  console.error('usage: export-rdf.ts <domain-directory> [-o <file>] [--base <iri>] [--instances] [--limit <n>]')
  process.exit(2)
}
const outIndex = args.indexOf('-o')
const out = outIndex === -1 ? undefined : args[outIndex + 1]
const baseIndex = args.indexOf('--base')
const base = baseIndex === -1 ? 'https://deepwork.example/ontology' : (args[baseIndex + 1] ?? '')
const limitIndex = args.indexOf('--limit')
const limit = limitIndex === -1 ? Infinity : Number(args[limitIndex + 1] ?? '0')

const graph = loadGraph(root)
const wanted = args.includes('--instances') ? Math.min(graph.objects.length, limit) : 0
const xml = render(graph, { base, instances: wanted })

if (out === undefined) {
  process.stdout.write(xml)
} else {
  writeFileSync(out, xml)
  // The summary goes to stderr so `-o` output stays byte-clean, and so a pipeline can see what it got
  // without parsing XML.
  console.error(
    `${out}: ${graph.schema.objectTypes.size} classes, ${graph.schema.linkTypes.size} relations, ` +
      `${wanted} instances, ${(Buffer.byteLength(xml) / 1024).toFixed(1)} KiB`,
  )
}
